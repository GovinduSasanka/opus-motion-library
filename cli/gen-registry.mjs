#!/usr/bin/env node
// Scans src/motions/**/*.tsx for `export const <name> = defineMotion` and writes src/registry.ts,
// then bundles the registry for Node (fonts stubbed) and writes catalog.json (metadata only).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {enrich} from './meta.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const motionsDir = path.join(root, 'src', 'motions');
const files = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, {withFileTypes: true})) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walk(f);
    else if (/\.tsx?$/.test(e.name)) files.push(f);
  }
};
walk(motionsDir);
files.sort();

const imports = [];
const names = [];
const fileOf = {}; // export name -> src-relative file
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const found = [...src.matchAll(/export const (\w+) = defineMotion/g)].map((m) => m[1]);
  if (!found.length) continue;
  const rel = './' + path.relative(path.join(root, 'src'), f).split(path.sep).join('/').replace(/[.]tsx?$/, '');
  imports.push(`import {${found.join(', ')}} from '${rel}';`);
  names.push(...found);
  for (const n of found) fileOf[n] = rel.slice(2);
}
const reg = `// AUTO-GENERATED by cli/gen-registry.mjs — do not edit by hand.
import type {MotionDef} from './core/types';
${imports.join('\n')}

export const motions: MotionDef<any>[] = [
${names.map((n) => `  ${n},`).join('\n')}
];

export const registry: Record<string, MotionDef<any>> = Object.fromEntries(motions.map((m) => [m.id, m]));
`;
fs.writeFileSync(path.join(root, 'src', 'registry.ts'), reg);

// catalog.json: bundle the registry for node with browser-only modules stubbed
const out = path.join(root, 'node_modules', '.cache', 'mgl-catalog.mjs');
await build({
  entryPoints: [path.join(root, 'src', 'registry.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: out,
  logLevel: 'error',
  jsx: 'automatic',
  plugins: [
    {
      name: 'stub-fonts',
      setup(b) {
        b.onResolve({filter: /^@remotion\/google-fonts\//}, (a) => ({path: a.path, namespace: 'stub'}));
        b.onLoad({filter: /.*/, namespace: 'stub'}, () => ({contents: 'export const loadFont = () => ({fontFamily: "stub"});', loader: 'js'}));
      },
    },
  ],
});
const mod = await import('file://' + out.split(path.sep).join('/') + '?t=' + Date.now());
const ids = new Set();
const readJson = (f, fb) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : fb);
const overrides = readJson(path.join(root, 'docs', 'motion-meta.json'), {motions: {}}).motions ?? {};
const probe = readJson(path.join(root, 'docs', 'motion-probe.json'), {motions: {}}).motions ?? {};
for (const k of Object.keys(overrides)) if (!names.length || !mod.motions.some((m) => m.id === k)) console.warn(`motion-meta.json: unknown motion ${k}`);
const catalog = mod.motions.map((m, i) => {
  if (ids.has(m.id)) throw new Error(`duplicate motion id ${m.id}`);
  ids.add(m.id);
  const file = `src/${fileOf[names[i]]}.tsx`;
  const code = fs.readFileSync(path.join(root, file), 'utf8');
  const base = {
    id: m.id,
    title: m.title,
    category: m.category,
    description: m.description,
    useFor: m.useFor,
    source: m.source,
    durationInFrames: m.durationInFrames,
    tags: m.tags ?? [],
    props: Object.fromEntries(Object.entries(m.defaultProps).map(([k, v]) => [k, {default: v, doc: m.propDocs?.[k] ?? ''}])),
  };
  const o = {...(overrides[m.id] ?? {})};
  if (o.weight === undefined && /three-kit|@remotion\/three/.test(code)) o.weight = 'heavy';
  const {props, ...head} = base;
  return {...head, file, ...enrich(base, probe[m.id], o), props};
});
fs.writeFileSync(path.join(root, 'catalog.json'), JSON.stringify(catalog, null, 1));

// src/meta.ts: the runtime subset of the metadata (web players use it for loop / overlay defaults)
const lite = Object.fromEntries(catalog.map((m) => [m.id, {overlay: m.overlay, overlayProps: m.overlayProps, loopable: m.loopable, bestLength: m.bestLength, roles: m.roles, weight: m.weight}]));
fs.writeFileSync(
  path.join(root, 'src', 'meta.ts'),
  `// AUTO-GENERATED by cli/gen-registry.mjs from catalog.json — do not edit by hand.
import type {MotionMetaLite} from './web/types';

export const motionMeta: Record<string, MotionMetaLite> = ${JSON.stringify(lite, null, 1)};
`,
);
// src/web/loaders.ts: one dynamic import per motion (code-split web build)
fs.writeFileSync(
  path.join(root, 'src', 'web', 'loaders.ts'),
  `// AUTO-GENERATED by cli/gen-registry.mjs — do not edit by hand.
import type {MotionDef} from '../core/types';

export const loaders: Record<string, () => Promise<MotionDef<any>>> = {
${mod.motions
    .map((m, i) =>
      // motions that import Layers (e.g. mix) sit in a registry <-> Layers cycle: load them through the registry so
      // the registry module is always evaluated first (otherwise the code-split chunk sees them uninitialised)
      /from '\.\.\/\.\.\/(Layers|Compose|registry)'/.test(fs.readFileSync(path.join(root, 'src', fileOf[names[i]] + '.tsx'), 'utf8'))
        ? `  '${m.id}': () => import('../registry').then((x) => x.registry['${m.id}']),`
        : `  '${m.id}': () => import('../${fileOf[names[i]]}').then((x) => x.${names[i]} as MotionDef<any>),`,
    )
    .join('\n')}
};
`,
);
// src/recipes.ts: every recipes/*.json, so web players can play a recipe by id
const recipeDir = path.join(root, 'recipes');
const recipeList = fs.existsSync(recipeDir)
  ? fs.readdirSync(recipeDir).filter((f) => f.endsWith('.json')).sort().map((f) => {
      const r = JSON.parse(fs.readFileSync(path.join(recipeDir, f), 'utf8'));
      if (r.id !== f.replace(/\.json$/, '')) throw new Error(`recipes/${f}: id "${r.id}" must match the file name`);
      for (const l of [...(r.layers ?? []), ...(r.scenes ?? []).flatMap((s) => [s, ...(s.layers ?? [])]), ...(r.overlays ?? [])]) if (l.motion && !ids.has(l.motion)) throw new Error(`recipes/${f}: unknown motion ${l.motion}`);
      return r;
    })
  : [];
fs.writeFileSync(path.join(root, 'src', 'recipes.ts'), `// AUTO-GENERATED by cli/gen-registry.mjs from recipes/*.json — do not edit by hand.
import type {Recipe} from './web/types';

export const recipes: Recipe[] = ${JSON.stringify(recipeList, null, 1)} as Recipe[];
`);
// transitions.json: recommended frames per type/variant for node tools (cli/direct.mjs)
const tout = path.join(root, 'node_modules', '.cache', 'mgl-transitions.mjs');
await build({entryPoints: [path.join(root, 'src', 'transitions.tsx')], bundle: true, platform: 'node', format: 'esm', outfile: tout, logLevel: 'error', jsx: 'automatic'});
const tmod = await import('file://' + tout.split(path.sep).join('/') + '?t=' + Date.now());
fs.writeFileSync(path.join(root, 'transitions.json'), JSON.stringify(Object.fromEntries(Object.entries(tmod.DEFAULTS).map(([k, v]) => [k, v.frames])), null, 1));
// styles: src/styles/defs/**/*.ts exporting `defineStyle(...)` -> src/styles/registry.ts + styles.json
const styleDir = path.join(root, 'src', 'styles', 'defs');
const styleFiles = [];
const walkS = (d) => {
  if (!fs.existsSync(d)) return;
  for (const e of fs.readdirSync(d, {withFileTypes: true})) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walkS(f);
    else if (/\.tsx?$/.test(e.name)) styleFiles.push(f);
  }
};
walkS(styleDir);
styleFiles.sort();
const sImports = [];
const sNames = [];
for (const f of styleFiles) {
  const src = fs.readFileSync(f, 'utf8');
  const found = [...src.matchAll(/export const (\w+) = defineStyle/g)].map((m) => m[1]);
  if (!found.length) continue;
  const rel = './' + path.relative(path.join(root, 'src', 'styles'), f).split(path.sep).join('/').replace(/[.]tsx?$/, '');
  sImports.push(`import {${found.join(', ')}} from '${rel}';`);
  sNames.push(...found);
}
fs.writeFileSync(path.join(root, 'src', 'styles', 'registry.ts'), `// AUTO-GENERATED by cli/gen-registry.mjs — do not edit by hand.
import type {StyleDef} from './engine';
${sImports.join('\n')}

export const styleList: StyleDef[] = [
${sNames.map((n) => `  ${n},`).join('\n')}
];

export const styles: Record<string, StyleDef> = Object.fromEntries(styleList.map((s) => [s.id, s]));
`);
const sout = path.join(root, 'node_modules', '.cache', 'mgl-styles.mjs');
await build({entryPoints: [path.join(root, 'src', 'styles', 'registry.ts')], bundle: true, platform: 'node', format: 'esm', outfile: sout, logLevel: 'error', jsx: 'automatic', external: ['react', 'remotion']});
const smod = await import('file://' + sout.split(path.sep).join('/') + '?t=' + Date.now());
const sids = new Set();
const styleCatalog = smod.styleList.map((st) => {
  if (sids.has(st.id)) throw new Error(`duplicate style id ${st.id}`);
  sids.add(st.id);
  return {id: st.id, name: st.name, family: st.family, description: st.description, useFor: st.useFor, palette: st.palette, fonts: st.fonts ?? null, step: st.step ?? 1, tags: st.tags, source: st.source ?? 'original'};
});
fs.writeFileSync(path.join(root, 'styles.json'), JSON.stringify(styleCatalog, null, 1));
console.log(`registry: ${names.length} motions from ${files.length} files -> src/registry.ts, catalog.json, src/meta.ts, src/web/loaders.ts; ${recipeList.length} recipes -> src/recipes.ts; ${styleCatalog.length} styles -> src/styles/registry.ts, styles.json`);
