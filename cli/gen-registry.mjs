#!/usr/bin/env node
// Scans src/motions/**/*.tsx for `export const <name> = defineMotion` and writes src/registry.ts,
// then bundles the registry for Node (fonts stubbed) and writes catalog.json (metadata only).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const motionsDir = path.join(root, 'src', 'motions');
const files = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, {withFileTypes: true})) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walk(f);
    else if (/\.tsx?$/.test(e.name)) files.push(f);
  }
};
walk(motionsDir);
files.sort();

const imports = [];
const names = [];
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const found = [...src.matchAll(/export const (\w+) = defineMotion/g)].map((m) => m[1]);
  if (!found.length) continue;
  const rel = './' + path.relative(path.join(root, 'src'), f).split(path.sep).join('/').replace(/[.]tsx?$/, '');
  imports.push(`import {${found.join(', ')}} from '${rel}';`);
  names.push(...found);
}
const reg = `// AUTO-GENERATED by cli/gen-registry.mjs — do not edit by hand.
import type {MotionDef} from './core/types';
${imports.join('\n')}

export const motions: MotionDef<any>[] = [
${names.map((n) => `  ${n},`).join('\n')}
];

export const registry: Record<string, MotionDef<any>> = Object.fromEntries(motions.map((m) => [m.id, m]));
`;
fs.writeFileSync(path.join(root, 'src', 'registry.ts'), reg);

// catalog.json: bundle the registry for node with browser-only modules stubbed
const out = path.join(root, 'node_modules', '.cache', 'mgl-catalog.mjs');
await build({
  entryPoints: [path.join(root, 'src', 'registry.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: out,
  logLevel: 'error',
  jsx: 'automatic',
  plugins: [
    {
      name: 'stub-fonts',
      setup(b) {
        b.onResolve({filter: /^@remotion\/google-fonts\//}, (a) => ({path: a.path, namespace: 'stub'}));
        b.onLoad({filter: /.*/, namespace: 'stub'}, () => ({contents: 'export const loadFont = () => ({fontFamily: "stub"});', loader: 'js'}));
      },
    },
  ],
});
const mod = await import('file://' + out.split(path.sep).join('/') + '?t=' + Date.now());
const ids = new Set();
const catalog = mod.motions.map((m) => {
  if (ids.has(m.id)) throw new Error(`duplicate motion id ${m.id}`);
  ids.add(m.id);
  return {
    id: m.id,
    title: m.title,
    category: m.category,
    description: m.description,
    useFor: m.useFor,
    source: m.source,
    durationInFrames: m.durationInFrames,
    tags: m.tags ?? [],
    props: Object.fromEntries(Object.entries(m.defaultProps).map(([k, v]) => [k, {default: v, doc: m.propDocs?.[k] ?? ''}])),
  };
});
fs.writeFileSync(path.join(root, 'catalog.json'), JSON.stringify(catalog, null, 1));
// transitions.json: recommended frames per type/variant for node tools (cli/direct.mjs)
const tout = path.join(root, 'node_modules', '.cache', 'mgl-transitions.mjs');
await build({entryPoints: [path.join(root, 'src', 'transitions.tsx')], bundle: true, platform: 'node', format: 'esm', outfile: tout, logLevel: 'error', jsx: 'automatic'});
const tmod = await import('file://' + tout.split(path.sep).join('/') + '?t=' + Date.now());
fs.writeFileSync(path.join(root, 'transitions.json'), JSON.stringify(Object.fromEntries(Object.entries(tmod.DEFAULTS).map(([k, v]) => [k, v.frames])), null, 1));
console.log(`registry: ${names.length} motions from ${files.length} files -> src/registry.ts, catalog.json`);
