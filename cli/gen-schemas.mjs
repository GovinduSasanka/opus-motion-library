#!/usr/bin/env node
/**
 * gen-schemas — writes props-schema.json: one JSON Schema (draft 2020-12) per motion, derived from catalog.json.
 *
 *   node cli/gen-schemas.mjs                  -> props-schema.json   {version, motions: {<id>: schema}}
 *   node cli/gen-schemas.mjs --split schemas  -> also schemas/<id>.json (one file per motion)
 *   node cli/gen-schemas.mjs --check          -> exit 1 when props-schema.json is out of date
 *
 * Run it after `node cli/gen-registry.mjs` (npm run gen does both).
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {motionSchema} from './schema.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const flag = (n) => argv.includes(`--${n}`);
const val = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : undefined);

const catalog = JSON.parse(fs.readFileSync(path.join(root, 'catalog.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const motions = {};
for (const m of catalog) motions[m.id] = motionSchema(m);

const out = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  title: 'Opus Motion Library — props schemas',
  description: 'One JSON Schema per motion id describing its `props`. Generated by cli/gen-schemas.mjs from catalog.json.',
  version: pkg.version,
  count: catalog.length,
  motions,
};
const text = JSON.stringify(out) + '\n';
const file = path.join(root, 'props-schema.json');

if (flag('check')) {
  const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text;
  console.log(same ? 'props-schema.json is up to date' : 'props-schema.json is out of date: run node cli/gen-schemas.mjs');
  process.exit(same ? 0 : 1);
}

fs.writeFileSync(file, text);
console.log(`props-schema.json: ${catalog.length} schemas, ${(text.length / 1024).toFixed(0)} KB`);

const split = val('split');
if (split) {
  const dir = path.resolve(root, split);
  fs.mkdirSync(dir, {recursive: true});
  for (const [id, s] of Object.entries(motions)) fs.writeFileSync(path.join(dir, `${id}.json`), JSON.stringify(s, null, 1) + '\n');
  console.log(`${Object.keys(motions).length} files in ${path.relative(root, dir)}/`);
}
